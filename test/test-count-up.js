const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
let reduced = false, privacy = false, next = 0;
const frames = new Map();
const window = {
  matchMedia: () => ({ matches: reduced }),
  requestAnimationFrame: callback => { frames.set(++next, callback); return next; },
  cancelAnimationFrame: id => frames.delete(id)
};
const document = { hidden: false, body: { classList: { contains: name => name === 'privacy-mode-active' && privacy } } };
vm.runInNewContext(fs.readFileSync('public/js/count-up.js', 'utf8'), { window, document });
const element = { isConnected: true };
const format = value => value === null ? '—' : value.toFixed(2);
const step = time => {
  const callbacks = [...frames.values()];
  frames.clear();
  callbacks.forEach(callback => callback(time));
};
window.FundCountUp.render(element, 1234.567, format);
assert.equal(element.textContent, '0.00');
step(100); step(500);
assert.equal(element.textContent, '180.80', 'Quarter duration must start gently');
step(900);
assert.equal(element.textContent, '617.28', 'Half duration must reach half the value');
step(1300);
assert.equal(element.textContent, '1053.77', 'Last quarter must slow down smoothly');
step(1700);
assert.equal(element.textContent, '1234.57', 'End value must use exact source precision');
window.FundCountUp.render(element, -12.345, format);
step(1000); step(2600);
assert.equal(element.textContent, '-12.35');
window.FundCountUp.render(element, 9, format);
window.FundCountUp.render(element, 20, format, false);
step(2000);
assert.equal(element.textContent, '20.00', 'Refresh must cancel an in-flight animation');
assert.equal(frames.size, 0);
window.FundCountUp.render(element, null, format);
assert.equal(element.textContent, '—');
reduced = true;
window.FundCountUp.render(element, 50, format);
assert.equal(element.textContent, '50.00');
assert.equal(frames.size, 0);
reduced = false;
window.FundCountUp.render(element, 90, format);
step(3000); reduced = true; step(3100);
assert.equal(element.textContent, '90.00', 'Changing reduced-motion preference must finish immediately');
reduced = false;
privacy = true;
window.FundCountUp.render(element, 1234.567, format);
assert.equal(element.textContent, '1234.57', 'Privacy mode must render the final value without animation');
assert.equal(frames.size, 0);
privacy = false;
window.FundCountUp.render(element, 75, format);
step(4000);
privacy = true;
step(4100);
assert.equal(element.textContent, '75.00', 'A privacy change must stop an in-flight animation');
assert.equal(frames.size, 0);
privacy = false;
const second = { isConnected: true };
window.FundCountUp.render(element, 100, format);
window.FundCountUp.render(second, -20, format);
assert.equal(frames.size, 2, 'Both animations must be running before cancellation');
window.FundCountUp.finishAll();
assert.equal(element.textContent, '100.00');
assert.equal(second.textContent, '-20.00');
assert.equal(frames.size, 0, 'Enabling privacy must cancel every pending frame synchronously');
step(5000);
assert.equal(element.textContent, '100.00');
console.log('CountUp easing, precision, negative and unavailable values, cancellation, privacy mode and reduced motion passed.');
